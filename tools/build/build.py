"""Build every generated output from src/ and install/harnesses.yaml (install/OUTPUTS.md).

Usage:
  uv run python tools/build/build.py [--version V] [--out DIR] [--check]

  --version V  release version for every manifest, catalog, package, and skill (default: the CLI's
               lapis_design.__version__). A given version is refused when a release already used it
               (check_version says how the previous release tag is found).
  --out DIR    where the outputs go (default: the repository root). Writing also removes files under
               the generated paths that the build no longer produces.
  --check      build into a temporary directory and exit 1 listing every file under the generated
               paths that differs from, is missing in, or is extra in DIR. CI runs this.

Sources: src/skills, src/shared/index.yaml, src/agents, src/extensions, src/hermes, and
install/harnesses.yaml, whose `outputs` list every output with its path template. Skills and agents
that are listed in harnesses.yaml but not written yet are skipped. manifests.py emits the JSON
outputs; installers.py (when present) emits install.sh, install.ps1, and INSTALLATION.md.

Every skill, plugin, and the Hermes plugin folder also gets LICENSE and LICENSE-docs, copied from the
repository root, and every manifest and skill states the license expression of pyproject.toml.
"""
