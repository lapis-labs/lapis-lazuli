# The only paths the build writes, removes, or compares: prefixes ending in / and single files.
INSTALLER_PATHS = ("install/install.sh", "install/install.ps1", "INSTALLATION.md")
GENERATED = ("plugins/", "dist/", ".claude-plugin/marketplace.json", ".agents/plugins/marketplace.json",
             "package.json", *INSTALLER_PATHS)

# Sources, as the outputs' `from` in install/harnesses.yaml name them
SKILLS_DIR = "src/skills"
SHARED_DIR = "src/shared"
AGENTS_DIR = "src/agents"
EXTENSION = "src/extensions/session-start.ts"
HERMES_DIR = "src/hermes"

# Texts at the repository root, copied byte for byte into every folder that can be installed on its
# own (each plugin, each skill, the Hermes plugin), so a folder-only install still carries them. The
# project's license expression is `[project] license` in pyproject.toml, the one place it is written.
LICENSE_FILES = ("LICENSE", "LICENSE-docs")

SKILL_KEYS = {"name", "description", "license"}   # portable keys a source sets; the build adds metadata
DESCRIPTION_MAX = 1024
AGENT_KEYS = {"name", "description"}              # plugin agents ignore permissionMode, hooks, mcpServers
HERMES_KEYS = {"description", "provides_hooks"}   # the build adds name, version, and author

# src/shared/index.yaml views that are not plain copies (fields-for-lookup: each item's `lookup_fields`)
RULE_FIELDS = ("id", "why", "better", "keep_when")    # names-and-alternatives: what generators get


def _generated(*sources: str) -> str:
    return f"Generated by tools/build/build.py from {' and '.join(sources)}; edit the source, not this file."


class BuildError(Exception):
    pass


def _text(s: str) -> str:
    """LF line ends and a final newline."""
    s = s.replace("\r\n", "\n")
    return s if not s or s.endswith("\n") else s + "\n"


def _read(path: Path) -> str | bytes:
    data = path.read_bytes()
    try:
        return _text(data.decode("utf-8"))
    except UnicodeDecodeError:
        return data                          # binary reference files are copied as they are


def _load_yaml(path: Path, root: Path):
    try:
        return yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError) as exc:
        raise BuildError(f"{path.relative_to(root)}: {exc}") from None


def _yaml(data, header: list[str]) -> str:
    body = yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)
    return "".join(f"# {line}\n" for line in header) + body


def _title(path: Path) -> str:
    """A shared file's one-line summary: its first line (a # title in every YAML and Markdown file)."""
    with path.open(encoding="utf-8") as f:
        return f.readline().strip().lstrip("#").strip()


def _visible(entries):
    return sorted(e for e in entries if not e.name.startswith(".") and e.name != "__pycache__")


def _split_frontmatter(text: str, where: str) -> tuple[dict, str]:
    if not text.startswith("---\n"):
        raise BuildError(f"{where}: must start with a --- frontmatter block")
    end = text.find("\n---\n", 3)
    if end < 0:
        raise BuildError(f"{where}: frontmatter has no closing ---")
    try:
        meta = yaml.safe_load(text[4:end + 1])
    except yaml.YAMLError as exc:
        raise BuildError(f"{where}: frontmatter is not YAML: {exc}") from None
    if not isinstance(meta, dict):
        raise BuildError(f"{where}: frontmatter must be a mapping")
    return meta, text[end + 5:]


def _frontmatter(meta: dict, body: str) -> str:
    # one line per key, so line-based frontmatter readers see whole values
    return "---\n" + yaml.safe_dump(meta, sort_keys=False, allow_unicode=True, width=1_000_000) + "---\n" + body


def _description(meta: dict, where: str) -> str:
    desc = meta.get("description")
    if not isinstance(desc, str) or not desc.strip():
        raise BuildError(f"{where}: description must be a non-empty string")
    return desc


# ---------------------------------------------------------------- shared views

def _without_provenance(data):
    if isinstance(data, dict):
        return {k: _without_provenance(v) for k, v in data.items() if k != "provenance"}
    if isinstance(data, list):
        return [_without_provenance(v) for v in data]
    return data


def _without_top_level(text: str, key: str) -> str:
    """YAML text without its top-level `key:` block: the key's line, the indented or `-` lines under it,
    and the blank lines that follow. Every other line, comments included, stays as it is."""
    out: list[str] = []
    inside = False
    for line in text.splitlines(keepends=True):
        if inside and (not line.strip() or line[0] in " \t-"):
            continue
        inside = re.match(rf"{re.escape(key)}\s*:", line) is not None
        if not inside:
            out.append(line)
    return "".join(out)


def _full_view(root: Path, path: Path) -> str | bytes:
    """A shared file as it is, except that a YAML file loses its top-level `provenance`."""
    content = _read(path)
    if isinstance(content, bytes) or path.suffix not in (".yaml", ".yml"):
        return content
    kept = _without_top_level(content, "provenance")
    try:
        same = yaml.safe_load(kept) == _without_provenance(_load_yaml(path, root))
    except yaml.YAMLError:
        same = False
    if not same:
        raise BuildError(f"{path.relative_to(root)}: provenance must be a top-level key outside rules files, "
                         "so the full view can leave it out and keep the file's comments")
    return kept


def _refs(node, found: set[str]) -> None:
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("#/$defs/"):
            found.add(ref.removeprefix("#/$defs/"))
        for v in node.values():
            _refs(v, found)
    elif isinstance(node, list):
        for v in node:
            _refs(v, found)


def _lookup_view(item: dict, schema: dict) -> dict:
    fields = item.get("lookup_fields")
    if not fields:
        raise BuildError(f"src/shared/index.yaml: {item['id']} has a fields-for-lookup consumer but no lookup_fields")
    props = {k: v for k, v in schema["properties"].items() if k in fields}
    if missing := [f for f in fields if f not in props]:
        raise BuildError(f"{item['path']}: fields-for-lookup names {missing}, which the schema lacks")
    defs = schema.get("$defs", {})
    wanted: set[str] = set()
    _refs(props, wanted)
    pending = set(wanted)
    while pending:                                    # definitions reached through other definitions
        more: set[str] = set()
        _refs([defs[name] for name in pending if name in defs], more)
        pending = more - wanted
        wanted |= more
    out = {k: schema[k] for k in ("$schema", "title", "type") if k in schema}
    out["properties"] = props
    if required := [r for r in schema.get("required", []) if r in props]:
        out["required"] = required
    if wanted:
        out["$defs"] = {k: v for k, v in defs.items() if k in wanted}
    return out


def _view(root: Path, item: dict, view: str) -> str | bytes:
    path = root / SHARED_DIR / item["path"]
    if view == "full" and item["kind"] != "rules":
        return _full_view(root, path)
    data = _load_yaml(path, root)
    if item["kind"] == "rules" and view == "full":
        data = _without_provenance(data)
    elif item["kind"] == "rules" and view == "names-and-alternatives":
        data = {"version": data["version"], "as_of": data["as_of"],
                "rules": [{k: r[k] for k in RULE_FIELDS if k in r} for r in data["rules"]]}
    elif view == "fields-for-lookup":
        data = _lookup_view(item, data)
    else:
        raise BuildError(f"src/shared/index.yaml: no {view} view for {item['id']} ({item['kind']})")
    header = [f"{_title(path)} ({view} view)", _generated(f"{SHARED_DIR}/{item['path']}")]
    if view == "fields-for-lookup":
        header.append("Only the fields lookups read; validate plans against the full schema (lapis-design plan check).")
    return _yaml(_without_provenance(data), header)   # no view of any kind carries provenance


# ---------------------------------------------------------------- the build

class Build:
    def __init__(self, root: Path, doc: dict, version: str):
        self.root, self.doc, self.version = root, doc, version
        self.owner = {s: p for p in doc["plugins"] for s in p["skills"]}
        schema = _load_yaml(root / "install/harnesses.schema.yaml", root)
        slug = schema["$defs"]["slug"]
        self.slug = re.compile(slug["pattern"])
        self.slug_max = slug["maxLength"]

    @cached_property
    def license_id(self) -> str:
        """The project's SPDX license expression, from pyproject.toml."""
        path = self.root / "pyproject.toml"
        try:
            value = tomllib.loads(path.read_text(encoding="utf-8"))["project"]["license"]
        except (OSError, ValueError, KeyError) as exc:
            raise BuildError(f"pyproject.toml: cannot read [project] license ({exc})") from None
        if not isinstance(value, str) or not value.strip():
            raise BuildError("pyproject.toml: [project] license must be an SPDX expression string")
        return value

    @cached_property
    def license_texts(self) -> dict[str, bytes]:
        """File name -> the bytes of the repository's license text."""
        texts = {}
        for name in LICENSE_FILES:
            try:
                texts[name] = (self.root / name).read_bytes()
            except OSError as exc:
                raise BuildError(f"{name}: the license text is missing ({exc.strerror})") from None
        return texts

    def plugin_licenses(self) -> dict[str, bytes]:
        """plugins/<plugin>/LICENSE and LICENSE-docs for every plugin in install/harnesses.yaml."""
        return {f"plugins/{p['name']}/{name}": data for p in self.doc["plugins"]
                for name, data in self.license_texts.items()}

    @cached_property
    def shared(self) -> dict[str, dict[str, str | bytes]]:
        """skill -> files under its shared/ directory, from src/shared/index.yaml."""
        index = _load_yaml(self.root / SHARED_DIR / "index.yaml", self.root)
        views: dict[tuple[str, str], str | bytes] = {}
        listed: dict[str, list[dict]] = {}
        for item in index["items"]:
            if item.get("status") == "planned":       # not written yet
                continue
            for skill, view in item["consumers"].items():
                if skill not in self.owner:
                    raise BuildError(f"src/shared/index.yaml: {item['id']} names {skill}, which no plugin lists")
                if view == "none":
                    continue
                entry = {"id": item["id"], "view": view, "path": item["path"],
                         "summary": _title(self.root / SHARED_DIR / item["path"])}
                listed.setdefault(skill, []).append(entry)
                if view != "summary" and (item["id"], view) not in views:
                    views[item["id"], view] = _view(self.root, item, view)
        out: dict[str, dict[str, str | bytes]] = {}
        for skill, entries in listed.items():
            files = {e["path"]: views[e["id"], e["view"]] for e in entries if e["view"] != "summary"}
            files["index.yaml"] = _yaml({"version": index["version"], "skill": skill, "items": entries}, [
                f"Shared items for {skill}. " + _generated(f"{SHARED_DIR}/index.yaml"),
                "Each full or reduced view is the file at `path` next to this index. A summary item is listed",
                "here only; the lapis-design CLI carries every item in full at the same path.",
            ])
            out[skill] = files
        return out

    def _skill(self, src: Path) -> dict[str, str | bytes]:
        name = src.name
        where = f"{SKILLS_DIR}/{name}"
        if not self.slug.match(name) or len(name) > self.slug_max:
            raise BuildError(f"{where}: skill names are lowercase letters, digits, and single hyphens, "
                             f"at most {self.slug_max} characters")
        if name not in self.owner:
            raise BuildError(f"{where}: no plugin in install/harnesses.yaml lists this skill")
        files: dict[str, str | bytes] = {}
        for entry in _visible(src.iterdir()):
            if entry.name == "SKILL.md" and entry.is_file():
                continue
            if entry.name == "references" and entry.is_dir():
                for ref in _visible(entry.iterdir()):
                    if not ref.is_file():
                        raise BuildError(f"{where}/references/{ref.name}: references keep one level, no subdirectories")
                    files[f"references/{ref.name}"] = _read(ref)
                continue
            raise BuildError(f"{where}/{entry.name}: a skill holds only SKILL.md and references/ "
                             "(the build adds shared/)")
        skill_md = src / "SKILL.md"
        if not skill_md.is_file():
            raise BuildError(f"{where}: SKILL.md is missing")
        text = _read(skill_md)
        if not isinstance(text, str):
            raise BuildError(f"{where}/SKILL.md: not UTF-8 text")
        meta, body = _split_frontmatter(text, f"{where}/SKILL.md")
        if extra := sorted(set(meta) - SKILL_KEYS):
            raise BuildError(f"{where}/SKILL.md: frontmatter keys {extra} are not portable; a source sets only "
                             "name, description, and license (the build adds metadata)")
        if meta.get("name") != name:
            raise BuildError(f"{where}/SKILL.md: name {meta.get('name')!r} must equal the directory name {name!r}")
        desc = _description(meta, f"{where}/SKILL.md")
        if len(desc) > DESCRIPTION_MAX:
            raise BuildError(f"{where}/SKILL.md: description has {len(desc)} characters; the limit is {DESCRIPTION_MAX}")
        if meta.get("license") != self.license_id:
            raise BuildError(f"{where}/SKILL.md: license {meta.get('license')!r} must be the project's "
                             f"{self.license_id!r} (pyproject.toml); set `license: {self.license_id}`")
        out_meta = {"name": name, "description": desc, "license": self.license_id,
                    "metadata": {"plugin": self.owner[name]["name"], "version": str(self.version)}}
        files["SKILL.md"] = _frontmatter(out_meta, body)
        files.update(self.license_texts)
        if name == "ultramarine" and "critic" in self.agents:
            if "references/critic.md" in files:
                raise BuildError(f"{where}/references/critic.md: generated from {AGENTS_DIR}/critic.md")
            files["references/critic.md"] = self.agents["critic"][2].lstrip("\n")
        for rel, data in self.shared.get(name, {}).items():
            files[f"shared/{rel}"] = data
        return dict(sorted(files.items()))

    @cached_property
    def skills(self) -> dict[str, dict[str, str | bytes]]:
        """skill -> files of dist/skills/<skill>/, for every skill written in src/skills."""
        src = self.root / SKILLS_DIR
        if not src.is_dir():
            return {}
        out = {}
        for d in _visible(src.iterdir()):
            if not d.is_dir():
                raise BuildError(f"{SKILLS_DIR}/{d.name}: only skill directories belong here")
            out[d.name] = self._skill(d)
        return out

    @cached_property
    def agents(self) -> dict[str, tuple[dict, str, str]]:
        """agent -> (plugin, description, body), for every agent written in src/agents."""
        owner = {a: p for p in self.doc["plugins"] for a in p.get("agents", [])}
        src = self.root / AGENTS_DIR
        out = {}
        for f in _visible(src.iterdir()) if src.is_dir() else []:
            where = f"{AGENTS_DIR}/{f.name}"
            if not f.is_file() or f.suffix != ".md":
                raise BuildError(f"{where}: only <agent>.md files belong here")
            if f.stem not in owner:
                raise BuildError(f"{where}: no plugin in install/harnesses.yaml lists agent {f.stem}")
            meta, body = _split_frontmatter(_text(f.read_text(encoding="utf-8")), where)
            if extra := sorted(set(meta) - AGENT_KEYS):
                raise BuildError(f"{where}: frontmatter keys {extra} are not allowed; an agent sets only name and "
                                 "description")
            if meta.get("name") != f.stem:
                raise BuildError(f"{where}: name {meta.get('name')!r} must equal the file name {f.stem!r}")
            out[f.stem] = (owner[f.stem], _description(meta, where), body)
        return out

    # One method per output format that manifests.py does not own: output -> {path: content}

    def agent_skill(self, out: dict) -> dict[str, str | bytes]:
        files = {}
        for skill, content in self.skills.items():
            base = out["path"].format(skill=skill, plugin=self.owner[skill]["name"])
            files.update({base + rel: data for rel, data in content.items()})
        return files

    def _agent_plugins(self, out: dict) -> list[dict]:
        with_agents = [p for p in self.doc["plugins"] if p.get("agents")]
        if "only" in out and set(out["only"]) != {p["name"] for p in with_agents}:
            raise BuildError(f"install/harnesses.yaml: output {out['id']} must list exactly the plugins with agents")
        return with_agents

    def claude_agent(self, out: dict) -> dict[str, str]:
        files = {}
        for agent, (plugin, desc, body) in self.agents.items():
            if plugin in self._agent_plugins(out):
                path = out["path"].format(plugin=plugin["name"]) + f"{agent}.md"
                files[path] = _frontmatter({"name": agent, "description": desc}, body)
        return files

    def codex_agent(self, out: dict) -> dict[str, str]:
        return {out["path"] + f"{plugin['prefix']}{agent}.toml":
                manifests.codex_agent_toml(f"{plugin['prefix']}{agent}", desc, body.lstrip("\n"))
                for agent, (plugin, desc, body) in self.agents.items()}

    def ts_extension(self, out: dict) -> dict[str, str | bytes]:
        src = self.root / EXTENSION
        if not src.is_file():
            raise BuildError(f"{EXTENSION} is missing")
        return {out["path"]: _read(src)}

    def hermes_plugin(self, out: dict) -> dict[str, str | bytes]:
        src = self.root / HERMES_DIR
        manifest = src / "plugin.yaml"
        if not manifest.is_file() or not (src / "__init__.py").is_file():
            raise BuildError(f"{HERMES_DIR} needs plugin.yaml and __init__.py")
        source = _load_yaml(manifest, self.root)
        if not isinstance(source, dict) or set(source) != HERMES_KEYS:
            raise BuildError(f"{HERMES_DIR}/plugin.yaml: set exactly {sorted(HERMES_KEYS)} (the build adds name, "
                             "version, and author)")
        files: dict[str, str | bytes] = {out["path"] + "plugin.yaml": _yaml(
            manifests.hermes_plugin(self.doc, self.version, source),
            ["Hermes plugin manifest. " + _generated(f"{HERMES_DIR}/plugin.yaml", "install/harnesses.yaml")])}
        for f in _visible(src.iterdir()):
            if f.name == "plugin.yaml":
                continue
            if not f.is_file():
                raise BuildError(f"{HERMES_DIR}/{f.name}: the plugin is one flat directory")
            files[out["path"] + f.name] = _read(f)
        files.update({out["path"] + name: data for name, data in self.license_texts.items()})
        return files

    def agents_md_snippet(self, out: dict) -> dict[str, str]:
        servers = {name: cfg for p in self.doc["plugins"]
                   for name, cfg in (manifests.mcp_json(p) or {"mcpServers": {}})["mcpServers"].items()}
        mcp = "\n".join(f"- MCP server `{name}`: run `{' '.join([cfg['command'], *cfg['args']])}` over stdio. Register it "
                        f"in this harness's own MCP settings, for example "
                        f"`{json.dumps({'mcpServers': {name: cfg}}, ensure_ascii=False)}`."
                        for name, cfg in servers.items())
        text = (f"<!-- {self.doc['repo']['name']} {self.version}, from dist/AGENTS.snippet.md -->\n"
                "## LapisLazuli design skills\n\n"
                "- At the start of a design task, run `lazuli local fonts --summary` and read the local font "
                "inventory summary it prints before choosing fonts.\n"
                f"{mcp}\n"
                "- Both commands come with the lapis-design CLI; `lazuli doctor` checks the install.\n")
        return {out["path"]: text}

    FORMATS = {
        "agent-skill": agent_skill,
        "claude-agent": claude_agent,
        "codex-agent": codex_agent,
        "ts-extension": ts_extension,
        "hermes-plugin": hermes_plugin,
        "agents-md-snippet": agents_md_snippet,
    }


def scope() -> tuple[str, ...]:
    return GENERATED if installers else tuple(p for p in GENERATED if p not in INSTALLER_PATHS)


def _in_scope(path: str, prefixes: tuple[str, ...]) -> bool:
    return any(path.startswith(p) if p.endswith("/") else path == p for p in prefixes)


def collect(root: Path, version: str) -> dict[str, str | bytes]:
    """Every generated file: repo-relative path -> content, in path order."""
    doc = _load_yaml(root / "install/harnesses.yaml", root)
    build = Build(root, doc, version)
    if unknown := sorted({o["format"] for o in doc["outputs"]} - manifests.FORMATS - set(Build.FORMATS)):
        raise BuildError(f"install/harnesses.yaml: no emitter for output formats {unknown}")
    try:
        parts = [manifests.emit(doc, version, build.license_id), build.plugin_licenses()]
    except ValueError as exc:
        raise BuildError(f"install/harnesses.yaml: {exc}") from None
    for out in doc["outputs"]:
        if out["format"] in Build.FORMATS:
            parts.append(Build.FORMATS[out["format"]](build, out))
    if installers:
        parts.append(installers.generate(doc, version))
    files: dict[str, str | bytes] = {}
    for part in parts:
        for path, content in part.items():
            if path in files:
                raise BuildError(f"{path} is emitted twice")
            files[path] = content
    if stray := sorted(p for p in files if not _in_scope(p, scope())):
        raise BuildError(f"outside the generated paths: {stray}")
    return dict(sorted(files.items()))


# ---------------------------------------------------------------- versions, writing, and the check

def _git(root: Path, *args: str) -> str | None:
    try:
        done = subprocess.run(["git", "-C", str(root), *args], capture_output=True, text=True, check=False)
    except OSError:
        return None
    return done.stdout.strip() if done.returncode == 0 else None


def check_version(root: Path, version: str) -> None:
    """Refuse a release version that a release already used (install/OUTPUTS.md, Versions and channels).

    Release tags are v<version>. The previous release tag is the nearest v* tag behind HEAD,
    `git describe --tags --abbrev=0 --match 'v[0-9]*'`, started from HEAD's first parent when HEAD itself
    carries v<version>, so rebuilding a release at its own tag passes. The build refuses when that
    tag is v<version>, and also when v<version> names any commit other than HEAD (a release on another
    branch). Outside a git work tree, or without tags, there is nothing to compare.
    """
    head = _git(root, "rev-parse", "-q", "--verify", "HEAD^{commit}")
    if head is None:
        return
    tag = f"v{version}"
    tagged = _git(root, "rev-parse", "-q", "--verify", f"refs/tags/{tag}^{{commit}}")
    previous = _git(root, "describe", "--tags", "--abbrev=0", "--match", "v[0-9]*",
                    "HEAD^" if tagged == head else "HEAD")
    if previous == tag or tagged not in (None, head):
        which = "the previous release tag" if previous == tag else "an existing release tag"
        raise BuildError(f"version {version} is taken: {tag} is {which} (commit {tagged[:12]}). Every release needs "
                         "a new version, because a plugin version pins Claude Code and Codex installs until it changes")


def tree_files(out: Path, prefixes: tuple[str, ...]) -> set[str]:
    """Files under the generated paths in DIR: what git would commit there (tracked, or untracked and
    not ignored) when DIR is a work tree's top level, otherwise every file."""
    top = _git(out, "rev-parse", "--show-toplevel")
    if top and Path(top).resolve() == out.resolve():
        done = subprocess.run(["git", "-C", str(out), "ls-files", "-z", "--cached", "--others", "--exclude-standard",
                               "--", *prefixes], capture_output=True, check=True)
        return {n for n in done.stdout.decode("utf-8").split("\0") if n and (out / n).is_file()}
    found = set()
    for p in prefixes:
        path = out / p
        if p.endswith("/") and path.is_dir():
            found |= {f.relative_to(out).as_posix() for f in path.rglob("*") if f.is_file()}
        elif path.is_file():
            found.add(p)
    return found


def _bytes(content: str | bytes) -> bytes:
    return content.encode("utf-8") if isinstance(content, str) else content


def write(files: dict[str, str | bytes], out: Path) -> tuple[list[str], list[str]]:
    """Write the build into DIR and remove what it no longer produces. Returns (written, removed)."""
    prefixes = scope()
    removed = sorted(tree_files(out, prefixes) - set(files))
    for rel in removed:
        path = out / rel
        path.unlink()
        for parent in path.parents:                       # empty directories left inside plugins/ or dist/
            if parent == out or not _in_scope(parent.relative_to(out).as_posix() + "/", prefixes) or any(parent.iterdir()):
                break
            parent.rmdir()
    written = []
    for rel, content in files.items():
        path, data = out / rel, _bytes(content)
        if not (path.is_file() and path.read_bytes() == data):
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            written.append(rel)
        if rel.endswith(".sh"):
            path.chmod(0o755)                               # install.sh runs as ./install/install.sh too
    return written, removed


def check(files: dict[str, str | bytes], out: Path) -> list[tuple[str, str]]:
    """(problem, path) for every generated file that differs from, is missing in, or is extra in DIR."""
    with tempfile.TemporaryDirectory(prefix="lapis-build-") as tmp:
        write(files, Path(tmp))
        built = {rel: (Path(tmp) / rel).read_bytes() for rel in files}
    committed = tree_files(out, scope())
    problems = []
    for rel in sorted(set(built) | committed):
        if rel not in committed:
            problems.append(("missing", rel))
        elif rel not in built:
            problems.append(("extra", rel))
        elif (out / rel).read_bytes() != built[rel]:
            problems.append(("differs", rel))
    return problems


def main(argv: list[str] | None = None, root: Path = ROOT) -> int:
    ap = argparse.ArgumentParser(prog="build", description=__doc__.split("\n")[0])
    ap.add_argument("--version", help="release version (default: lapis_design.__version__)")
    ap.add_argument("--out", type=Path, default=root, help="output directory (default: the repository root)")
    ap.add_argument("--check", action="store_true", help="compare a fresh build with --out instead of writing")
    args = ap.parse_args(argv)
    try:
        if args.version:
            check_version(root, args.version)
            version = args.version
        else:
            from lapis_design import __version__ as version
        files = collect(root, version)
        if args.check:
            problems = check(files, args.out)
            if problems:
                print(f"build: {len(problems)} generated file(s) out of sync with src/ and install/harnesses.yaml:",
                      file=sys.stderr)
                for problem, rel in problems:
                    print(f"  {problem:8} {rel}", file=sys.stderr)
                print("Run `uv run python tools/build/build.py` and commit the result.", file=sys.stderr)
                return 1
            print(f"build: {len(files)} generated files match the sources (version {version})")
            return 0
        written, removed = write(files, args.out)
    except BuildError as exc:
        print(f"build: {exc}", file=sys.stderr)
        return 2
    print(f"build: version {version}, {len(files)} files, {len(written)} written, {len(removed)} removed"
          + "".join(f"\n  removed {rel}" for rel in removed))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
